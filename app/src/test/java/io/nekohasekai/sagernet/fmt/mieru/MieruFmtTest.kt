package io.nekohasekai.sagernet.fmt.mieru

import android.app.Application
import com.esotericsoftware.kryo.io.ByteBufferInput
import com.esotericsoftware.kryo.io.ByteBufferOutput
import io.nekohasekai.sagernet.database.ProxyEntity
import io.nekohasekai.sagernet.fmt.KryoConverters
import io.nekohasekai.sagernet.ktx.applyDefaultValues
import libcore.Libcore
import org.junit.Assert.*
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config
import org.robolectric.annotation.Implementation
import org.robolectric.annotation.Implements

@Implements(value = Libcore::class, isInAndroidSdk = false)
class MieruLogShadow {
    companion object {
        @JvmStatic @Implementation fun __staticInitializer__() = Unit
        @JvmStatic @Implementation fun nekoLogPrintln(message: String) = Unit
    }
}

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [28], application = Application::class, shadows = [MieruLogShadow::class], instrumentedPackages = ["libcore"])
class MieruFmtTest {
    companion object {
        // Generated by the official v3.39.0 appctl URL encoders.
        const val SIMPLE = "mierus://user%3Aname:sample+%3A%25%40pass@[2001:db8::1]?mtu=1300&multiplexing=MULTIPLEXING_HIGH&port=443&port=8443-8445&profile=Official+fixture&protocol=TCP&protocol=TCP"
        const val PROTOBUF = "mieru://ClsKEE9mZmljaWFsIGZpeHR1cmUSGwoJdXNlcjpuYW1lEg5zYW1wbGUrOiVAcGFzcxojCgsyMDAxOmRiODo6MRoFCLsDEAIaDRACGgk4NDQzLTg0NDUglAoqAggEEhBPZmZpY2lhbCBmaXh0dXJl"
    }

    private fun assertOfficial(bean: MieruBean) {
        assertEquals("2001:db8::1", bean.serverAddress)
        assertEquals("user:name", bean.username)
        assertEquals("sample+:%@pass", bean.password)
        assertEquals("Official fixture", bean.name)
        assertEquals(listOf("443", "8443-8445"), bean.serverPorts)
        assertEquals("MULTIPLEXING_HIGH", bean.multiplexing)
        assertEquals(1300, bean.mtu.toInt())
    }

    @Test fun officialSimpleLinkPreservesEscapedCredentialsAndRanges() {
        assertOfficial(parseMieruSimpleLink(SIMPLE))
    }

    @Test fun officialProtobufPreservesProfileAndMultiplexing() {
        assertOfficial(parseMieruStandardLink(PROTOBUF).single())
    }

    @Test fun exportAndClonePreserveNativeFields() {
        val bean = parseMieruSimpleLink(SIMPLE).apply {
            name = "测试节点"
            handshakeMode = "HANDSHAKE_NO_WAIT"
        }
        val roundTrip = parseMieruSimpleLink(bean.toUri())
        val clone = bean.clone()
        for (copy in listOf(roundTrip, clone)) {
            assertEquals(bean.username, copy.username)
            assertEquals(bean.password, copy.password)
            assertEquals(bean.name, copy.name)
            assertEquals(bean.serverPorts, copy.serverPorts)
            assertEquals(bean.handshakeMode, copy.handshakeMode)
        }
    }

    @Test fun mixedTransportBindingsBecomeTwoUsableNodes() {
        val nodes = parseMieruSimpleLinks("mierus://user:pass@localhost?profile=Mixed&port=443&protocol=TCP&port=444&protocol=UDP")
        assertEquals(listOf("TCP", "UDP"), nodes.map { it.protocol })
        assertEquals(listOf(443,444), nodes.map { it.serverPort })
    }

    @Test fun nativeOutboundUsesOnePortRepresentationAndNoPlugin() {
        val bean = parseMieruSimpleLink(SIMPLE)
        val outbound = bean.toMieruOutbound()
        assertEquals("mieru", outbound.type)
        assertNull(outbound.server_port)
        assertEquals(listOf("443", "8443-8445"), outbound.server_ports)
        assertFalse(ProxyEntity().apply { putBean(bean) }.needExternal())
        assertTrue(ProxyEntity().apply { putBean(bean) }.toStdLink().startsWith("mierus://"))
    }

    @Test fun singlePortChangesAreNotShadowedByStaleRange() {
        val bean = MieruBean().applyDefaultValues().apply {
            serverAddress = "example.com"; serverPort = 443; username = "user"; password = "pass"
        }
        bean.serverPort = 8443
        val outbound = bean.toMieruOutbound()
        assertEquals(8443, outbound.server_port.toInt())
        assertNull(outbound.server_ports)
    }

    @Test fun legacyVersionZeroTcpAndUdpRemainReadable() {
        for (transport in listOf("TCP", "UDP")) {
            val buffer = ByteBufferOutput(1024)
            buffer.writeInt(0)
            buffer.writeString("example.com")
            buffer.writeInt(443)
            buffer.writeString(transport)
            buffer.writeString("old-user")
            buffer.writeString("old-pass")
            if (transport == "UDP") buffer.writeInt(1300)
            buffer.writeInt(1)
            buffer.writeString("Legacy")
            buffer.writeString("")
            buffer.writeString("")
            val restored = KryoConverters.deserialize(MieruBean(), buffer.toBytes())
            assertEquals(transport, restored.protocol)
            assertEquals("Legacy", restored.name)
            assertEquals("old-user", restored.username)
            assertEquals(if (transport == "UDP") 1300 else 1400, restored.mtu.toInt())
            assertTrue(restored.serverPorts.isEmpty())
            assertEquals("mieru", restored.toMieruOutbound().type)
        }
    }

    @Test fun invalidPortsAndCredentialsAreRejected() {
        for (port in listOf("0", "65536", "65535-2", "1-65536", "bad")) {
            assertThrows(IllegalArgumentException::class.java) {
                parseMieruSimpleLink("mierus://user:pass@localhost?port=$port&protocol=TCP")
            }
        }
        assertThrows(IllegalArgumentException::class.java) {
            parseMieruSimpleLink("mierus://user:@localhost?port=443&protocol=TCP")
        }
    }

    @Test fun truncatedProtobufIsRejected() {
        assertThrows(IllegalArgumentException::class.java) { parseMieruStandardLink("mieru://CgY=") }
    }
}
